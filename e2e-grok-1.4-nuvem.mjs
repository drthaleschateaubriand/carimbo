import { chromium } from 'playwright-core';
import fs from 'fs';
const code = decodeURIComponent(fs.readFileSync('/workspace/c14/fav-live.txt', 'utf8').replace(/^javascript:/, ''));
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] });
const page = await (await browser.newContext()).newPage();
await page.goto('http://127.0.0.1:8801/iframe.html'); await page.waitForTimeout(300);
await page.evaluate(code);
const pp = page.waitForEvent('popup');
await page.evaluate(() => document.getElementById('carimbarEnviarIA').click());
const pop = await pp; await pop.waitForLoadState('load');
await pop.waitForFunction(() => /Página enviada/.test(document.getElementById('log').textContent), null, { timeout: 30000 });
const sessao = await pop.textContent('#sessao');
console.log('ENVIADA', new Date().toISOString(), 'sessao', sessao, await pop.textContent('#log'));
const t0 = Date.now();
await page.frames().find(f => f.url().endsWith('form-transicao.html')).waitForFunction(() => document.querySelector('[name=cdPa]').value !== '', null, { timeout: 240000 });
const fr = page.frames().find(f => f.url().endsWith('form-transicao.html'));
const v = await fr.evaluate(() => ({ pa: document.querySelector('[name=cdPa]').value, fc: document.querySelector('[name=nrFc]').value, risco: document.querySelector('[name=tpRisco]').value, transicao: document.querySelector('[name=dsTransicao]').value }));
await page.waitForTimeout(800);
const resumo = await page.evaluate(() => document.getElementById('carimbarResumo').textContent);
await page.screenshot({ path: '/workspace/c14/p14-nuvem-live.png' });
console.log('PREENCHIDO', JSON.stringify(v), 'RESUMO', resumo, 'IA', await page.textContent('#carimbarIA'));
await browser.close();
